-- Migration: Bellami Stores schema
-- Purpose: Supplier stores identity, product ownership, supplier price snapshots,
--          return batches, and supplier payment settlements.
-- Also seeds default store id=1 so store_id FKs are never null.

-- ---------------------------------------------------------------------------
-- stores
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE,
  fullname TEXT,
  username TEXT,
  avatar TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stores_email ON stores (email);
CREATE INDEX IF NOT EXISTS idx_stores_status ON stores (status);

COMMENT ON TABLE stores IS
  'Supplier store identity (1 Clerk user ≈ 1 store). Row id=1 is the default fallback store.';

-- Default store (#1): prevents NULL / FK violations when adding store_id columns
